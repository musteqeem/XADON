const mumaker = require('mumaker');
const BOT_NAME = process.env.BOT_NAME || 'XADON AI';
module.exports = {
    name: "hackerx",
    alias: ['anontext', 'cyberavatar'],
    desc: 'Anonymous hacker avatar text',
    category: 'Media-Modifier',
    usage: ".hackerx <text>",
    examples: [".hackerx XADON"],
    execute: async (sock, m, { args, reply, prefix }) => {
        await sock.sendMessage(m.chat, { react: { text: '🎭', key: m.key } });
        const text = args.join(" ").trim();
        if (!text) return reply(`✦ *${BOT_NAME} HACKER*\n│ ❏ ${prefix}hackerx <text>\n_Powered by ${BOT_NAME}_`);
        try {
            const result = await mumaker.ephoto('https://en.ephoto360.com/create-anonymous-hacker-avatars-cyan-neon-677.html', text);
            if (!result || !result.image) throw new Error("No image URL received from the API");
            await sock.sendMessage(m.chat, { image: { url: result.image }, caption: `🎭 _Hacker avatar: ${text}_\n_Generated by ${BOT_NAME}_` }, { quoted: m });
            await sock.sendMessage(m.chat, { react: { text: '🌟', key: m.key } });
        } catch (err) {
            await sock.sendMessage(m.chat, { react: { text: '✘', key: m.key } });
            return reply(`✦ *${BOT_NAME} ERROR*\n│ ❏ ${err.message}`.slice(0, 400));
        }
    }
};
