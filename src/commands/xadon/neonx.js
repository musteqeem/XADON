const mumaker = require('mumaker');
const BOT_NAME = process.env.BOT_NAME || 'XADON AI';
module.exports = {
    name: "neonx",
    alias: ['neonwings', 'devilneon'],
    desc: 'Neon devil-wings text effect',
    category: "Textmaker",
    usage: ".neonx <text>",
    examples: [".neonx XADON"],
    execute: async (sock, m, { args, reply, prefix }) => {
        await sock.sendMessage(m.chat, { react: { text: '💫', key: m.key } });
        const text = args.join(" ").trim();
        if (!text) return reply(`✦ ───── ⋆⋅☆⋅⋆ ───── ✦\n ֎ *${BOT_NAME} NEON WINGS*\n✦ ───── ⋆⋅☆⋅⋆ ───── ✦\n╭─֎ *USAGE*\n│ ❏ ${prefix}neonx <text>\n╰─────────────────────────╯\n_Powered by ${BOT_NAME}_`);
        try {
            const result = await mumaker.ephoto('https://en.ephoto360.com/neon-devil-wings-text-effect-online-683.html', text);
            if (!result || !result.image) throw new Error("No image URL received from the API");
            await sock.sendMessage(m.chat, { image: { url: result.image }, caption: `💫 _Neon wings: ${text}_\n_Generated by ${BOT_NAME}_` }, { quoted: m });
            await sock.sendMessage(m.chat, { react: { text: '🌟', key: m.key } });
        } catch (err) {
            await sock.sendMessage(m.chat, { react: { text: '✘', key: m.key } });
            return reply(`✦ *${BOT_NAME} ERROR*\n│ ❏ ${err.message}`.slice(0, 400));
        }
    }
};
